/** Odmiana: 1 punkt, 2 punkty, 5 punktów. */
export function plural(n: number, one: string, few: string, many: string): string {
  const d = n % 10;
  const h = n % 100;
  const w = n === 1 ? one : d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
  return `${n.toLocaleString("pl-PL")} ${w}`;
}

