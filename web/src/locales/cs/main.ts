/** Skloňování: 1 bod, 2–4 body, 5 bodů. */
export function plural(n: number, one: string, few: string, many: string): string {
  const w = n === 1 ? one : n >= 2 && n <= 4 ? few : many;
  return `${n.toLocaleString("cs-CZ")} ${w}`;
}

