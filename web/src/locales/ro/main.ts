/** 1 punct, 2–19 puncte, 20 de puncte (și 101 puncte, 120 de puncte). */
export function plural(n: number, one: string, many: string): string {
  if (n === 1) return `1 ${one}`;
  const h = n % 100;
  return `${n.toLocaleString("ro-RO")} ${n !== 0 && (h === 0 || h >= 20) ? "de " : ""}${many}`;
}

